#!/usr/bin/env python3
"""
gen_boot_rom.py — Generate the ASIC boot ROM (openlane/designs/picosoc/src/boot_rom.v)
from bootloader.hex (the $readmemh format written by makehex.py: one 32-bit
word in plain hex per line, upper nibble first).

Why this exists: openlane/designs/picosoc/src/system.v used to instantiate
u_boot_sram (a sky130 SRAM macro) as the boot ROM, with web0 tied to 1'b1 and
din0 tied to 33'b0 — i.e. nothing can ever write the bootloader into it, so on
real silicon it powers up with whatever garbage the macro resets to and the
chip never boots (P1). A ROM whose contents are baked into the netlist at
synthesis time (this script's output) has no such hole: there is no write
port to leave disconnected.

Port shape matches how system.v drove u_boot_sram: clk0, csb0 (active-low),
addr0, dout0, with the same 1-cycle registered read latency (address sampled
on the clock edge csb0 is low, data available the following cycle — see
system.v's `boot_csb`/APB SETUP-ACCESS phasing). dout0 is 32 bits because
that's all system.v ever reads from boot_dout (the sky130 macro's 33rd
"spare" bit was always discarded).

Usage:
    python3 gen_boot_rom.py [bootloader.hex] [boot_rom.v]

Defaults: bootloader.hex -> ../openlane/designs/picosoc/src/boot_rom.v
(paths relative to this script, i.e. firmware/).
"""
import sys
import os

BOOT_SIZE = 1024  # words (4 KB), matches BOOT_SIZE in system.v


def gen(hex_path, out_path):
    with open(hex_path) as f:
        lines = [ln.strip() for ln in f if ln.strip()]

    if len(lines) > BOOT_SIZE:
        sys.exit(f"ERROR: {hex_path} has {len(lines)} words, exceeds "
                  f"BOOT_SIZE={BOOT_SIZE} (4 KB boot ROM)")

    for i, ln in enumerate(lines):
        if len(ln) != 8 or any(c not in "0123456789abcdefABCDEF" for c in ln):
            sys.exit(f"ERROR: {hex_path} line {i+1} is not 8 hex digits: {ln!r}")

    words = [ln.lower() for ln in lines]
    # Drop trailing all-zero words: they're already covered by `default`.
    while words and words[-1] == "00000000":
        words.pop()

    with open(out_path, "w") as f:
        f.write(
            "// AUTO-GENERATED by firmware/gen_boot_rom.py from "
            f"{os.path.basename(hex_path)} — DO NOT EDIT BY HAND.\n"
            f"// Source: {len(lines)} words ({len(lines)*4} B), "
            f"{len(words)} non-zero words emitted, rest default to 0.\n"
            "// Regenerate:  cd firmware && python3 gen_boot_rom.py\n"
            "`default_nettype none\n\n"
            "module boot_rom (\n"
            "    input  wire        clk0,\n"
            "    input  wire        csb0,\n"
            "    input  wire [10:0] addr0,\n"
            "    output reg  [31:0] dout0\n"
            ");\n\n"
            "    always @(posedge clk0) begin\n"
            "        if (!csb0) begin\n"
            "            case (addr0)\n"
        )
        for i, w in enumerate(words):
            f.write(f"                11'd{i}: dout0 <= 32'h{w};\n")
        f.write(
            "                default: dout0 <= 32'h00000000;\n"
            "            endcase\n"
            "        end\n"
            "    end\n\n"
            "endmodule\n"
        )

    print(f"[boot_rom] {out_path}: {len(lines)} words from {hex_path} "
          f"({len(words)} non-zero, {BOOT_SIZE - len(lines)} implicitly zero)")


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    hex_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "bootloader.hex")
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        here, "..", "openlane", "designs", "picosoc", "src", "boot_rom.v")
    gen(hex_path, out_path)
